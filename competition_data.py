def all_sets() -> List[Dict]:
    return [
        {"id": "primary", "name": "小学必背精选", "poems": PRIMARY},
        {"id": "middle_high", "name": "初高中必背精选", "poems": MIDDLE_HIGH},
        {"id": "ci_extra", "name": "词牌拓展", "poems": CI_EXTRA},
    ]


def all_poems() -> List[Dict]:
    poems = []
    for s in all_sets():
        poems.extend(s["poems"])
    return poems


def library_summary() -> str:
    sets = all_sets()
    n_poems = sum(len(s["poems"]) for s in sets)
    n_lines = sum(len(p["lines"]) for s in sets for p in s["poems"])
    parts = "、".join(f"{s['name']}{len(s['poems'])}首" for s in sets)
    return f"共 {n_poems} 首（{n_lines} 句）：{parts}"
